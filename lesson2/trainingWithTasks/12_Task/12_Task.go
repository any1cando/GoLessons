//12. Счётчик посещений — гонка данных и atomic
//Несколько горутин одновременно увеличивают общий счётчик посещений.
//- Создай общий счётчик типа int64.
//- Запусти 10 горутин.
//- Каждая увеличивает счётчик 1000 раз.
//- Дождись всех через WaitGroup и выведи результат.
//Сначала намеренно используй обычное увеличение и запусти:
//go run -race main.go
//
//Затем исправь доступ к счётчику с помощью sync/atomic.
//Ожидаемый результат после исправления — ровно 10000, без сообщений о гонке. Даже если неправильный
//вариант иногда выдаёт 10000, это не означает, что гонки нет.

package main

import (
	"fmt"
	"sync"
	"sync/atomic"
)

func main() {

	var counter atomic.Int64
	wg := &sync.WaitGroup{}

	for range 10 {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for range 1000 {
				counter.Add(1)
			}
		}()
	}
	wg.Wait()
	fmt.Println(counter.Load())

}
